"""Render planning/prepd-work-plan.md to planning/prepd-work-plan.html (stdlib only).

The .md file is the single source of truth; never edit the .html by hand.
Usage: python planning/build_plan_html.py
Handles only the Markdown the plan uses: headings, paragraphs, tables, lists, **bold**, `code`.
"""
import html
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
SRC = HERE / "prepd-work-plan.md"
OUT = HERE / "prepd-work-plan.html"

CSS = """
:root{--bg:#fafaf9;--fg:#1c1917;--mut:#57534e;--line:#e7e5e4;--head:#f5f5f4;--done:#15803d;--prog:#b45309;--todo:#78716c;--acc:#1d4ed8}
@media (prefers-color-scheme:dark){:root{--bg:#1c1917;--fg:#f5f5f4;--mut:#a8a29e;--line:#44403c;--head:#292524;--done:#4ade80;--prog:#fbbf24;--todo:#a8a29e;--acc:#93c5fd}}
body{background:var(--bg);color:var(--fg);font:15px/1.55 system-ui,sans-serif;max-width:1100px;margin:0 auto;padding:16px}
h1{font-size:1.7em}h2{margin-top:2em;border-bottom:1px solid var(--line);padding-bottom:.2em}h3{margin-top:1.5em}
.tbl{overflow-x:auto}table{border-collapse:collapse;width:100%;margin:.6em 0;font-size:.92em}
th,td{border:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}th{background:var(--head)}
code{background:var(--head);padding:1px 4px;border-radius:3px;font-size:.9em}
.st{font-weight:600;white-space:nowrap}.done{color:var(--done)}.prog{color:var(--prog)}.todo{color:var(--todo)}
.summary{display:flex;gap:24px;flex-wrap:wrap;background:var(--head);padding:12px 16px;border-radius:8px}
.bar{height:8px;background:var(--line);border-radius:4px;width:220px;margin-top:4px}.bar>i{display:block;height:100%;background:var(--done);border-radius:4px}
.gen{color:var(--mut);font-size:.85em}
"""


def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    return re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)


def status_cell(t):
    cls = "done" if t.startswith("Done") else "prog" if t.startswith("In progress") else "todo"
    return f'<span class="st {cls}">{inline(t)}</span>'


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def render(md):
    out, lines, i = [], md.splitlines(), 0
    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
        elif m := re.match(r"(#{1,4}) (.*)", ln):
            n = len(m.group(1))
            out.append(f"<h{n}>{inline(m.group(2))}</h{n}>")
            i += 1
        elif ln.startswith("|"):
            head = cells(ln)
            st = head.index("Status") if "Status" in head else -1
            rows = []
            i += 2  # skip header and separator
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(cells(lines[i]))
                i += 1
            th = "".join(f"<th>{inline(c)}</th>" for c in head)
            trs = "".join(
                "<tr>" + "".join(f"<td>{status_cell(c) if k == st else inline(c)}</td>" for k, c in enumerate(r)) + "</tr>"
                for r in rows
            )
            out.append(f'<div class="tbl"><table><tr>{th}</tr>{trs}</table></div>')
        elif re.match(r"(\d+\.|-) ", ln):
            tag = "ol" if ln[0].isdigit() else "ul"
            items = []
            while i < len(lines) and re.match(r"(\d+\.|-) ", lines[i]):
                items.append(re.sub(r"^(\d+\.|-) ", "", lines[i]))
                i += 1
            out.append(f"<{tag}>" + "".join(f"<li>{inline(x)}</li>" for x in items) + f"</{tag}>")
        else:
            para = []
            while i < len(lines) and lines[i].strip() and not re.match(r"(#|\||\d+\. |- )", lines[i]):
                para.append(lines[i])
                i += 1
            out.append("<p>" + "<br>".join(inline(x) for x in para) + "</p>")
    return "\n".join(out)


def progress(md, prefix):
    rows = [cells(l) for l in md.splitlines() if re.match(rf"\| {prefix}\d+ \|", l)]
    done = sum(r[-1].startswith("Done") for r in rows)
    return done, len(rows)


def build(md):
    pd, pt = progress(md, "P")
    md_, mt = progress(md, "M")
    summary = "".join(
        f'<div><strong>{label}: {d}/{t} done</strong><div class="bar"><i style="width:{100 * d // max(t, 1)}%"></i></div></div>'
        for label, d, t in (("Milestones", md_, mt), ("Products", pd, pt))
    )
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>PREPD Work Plan</title><style>{CSS}</style></head><body>"
        f'<div class="summary">{summary}</div>{render(md)}'
        f'<p class="gen">Generated from planning/prepd-work-plan.md. Do not edit this file.</p></body></html>'
    )


def _check():
    sample = "# T\n\n| # | Status |\n|---|---|\n| P1 | Done 2026-11-04 |\n| P2 | Not started |\n\n- a **b**\n"
    out = build(sample)
    assert '<span class="st done">Done 2026-11-04</span>' in out
    assert "Products: 1/2 done" in out and "<li>a <strong>b</strong></li>" in out


if __name__ == "__main__":
    _check()
    OUT.write_text(build(SRC.read_text(encoding="utf8")), encoding="utf8")
    print(f"Wrote {OUT}", file=sys.stderr)
